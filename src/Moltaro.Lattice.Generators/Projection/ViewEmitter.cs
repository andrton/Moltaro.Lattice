using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Moltaro.Lattice.Generators.Metadata;
using Moltaro.Lattice.Schema;

namespace Moltaro.Lattice.Generators.Projection;

// The generated record and owned views hold a borrowed reader and a span of bound handles.
// Every type uses offsets local to that span, so sibling fields can share an owned view
// type even when the handles come from different points in the projection.
internal sealed class ViewEmitter(Compilation compilation, INamedTypeSymbol view, INamedTypeSymbol entity, ViewField[] fields)
{
    private const string Access = "global::Moltaro.Lattice.Access.";
    private const string Schema = "global::Moltaro.Lattice.Schema.";
    private const string Span = "global::System.ReadOnlySpan<global::Moltaro.Lattice.Schema.LatticeField>";

    private readonly StringBuilder _source = new();
    private readonly ViewTypeNames _types = new(compilation);
    private readonly List<(string Name, ViewField Field)> _ownedViews = [];

    private HashSet<string> _names = null!;
    private string _record = null!;
    private string _handles = null!;
    private int _indent;

    public string Emit()
    {
        _names = new HashSet<string>(view.GetMembers().Select(member => member.Name), StringComparer.Ordinal) { view.Name };
        foreach (var field in fields)
        {
            if (!_names.Add(field.Name))
            {
                throw ProjectionBuilder.Failure(field.Path, "the view already has a member of this name");
            }
        }

        ReserveChildNames(fields);
        _record = UnusedName("_record");
        _handles = UnusedName("_fields");
        var paths = UnusedName("_paths");
        var containers = Containers().ToArray();
        if (!view.ContainingNamespace.IsGlobalNamespace)
        {
            Line($"namespace {view.ContainingNamespace.ToDisplayString()};");
            Line();
        }

        foreach (var container in containers)
        {
            Open(Declaration(container));
        }

        var name = Name(view);
        var contract = $"{Access}ILatticeEntityView<{name}, {Qualified(entity)}>";
        Open($"{Declaration(view)} : {contract}");
        Line($"private static readonly {Access}LatticeViewField[] {paths} =");
        Line("[");
        _indent++;
        WritePaths(fields);
        _indent--;
        Line("];");
        Line();
        WriteStorage("@" + view.Name, "LatticeRecordView", "private");
        Line($"static global::System.ReadOnlySpan<{Access}LatticeViewField> {contract}.Fields => {paths};");
        Line($"static {name} {contract}.Create({Access}LatticeRecordView record, {Span} fields) => new(record, fields);");
        WriteProperties(fields);

        for (var index = 0; index < _ownedViews.Count; index++)
        {
            var owned = _ownedViews[index];
            Line();
            Open($"public readonly ref struct {owned.Name}");
            WriteStorage(owned.Name, "LatticeOwnedView", "internal");

            if (owned.Field.Children.Length > 0)
            {
                WriteProperties(owned.Field.Children);
            }

            Close();
        }

        Close();
        foreach (var unused in containers)
        {
            Close();
        }

        var header = new StringBuilder().AppendLine("// <auto-generated />").AppendLine("#nullable enable");
        foreach (var alias in _types.UsedAliases)
        {
            header.Append("extern alias @").Append(alias).AppendLine(";");
        }

        return header.Append(_source).ToString();
    }

    private void WriteStorage(string typeName, string recordType, string ctorAccess)
    {
        Line($"private readonly {Access}{recordType} {_record};");
        Line($"private readonly {Span} {_handles};");
        Line();
        Open($"{ctorAccess} {typeName}({Access}{recordType} record, {Span} fields)");
        Line($"{_record} = record;");
        Line($"{_handles} = fields;");
        Close();
        Line();
    }

    private void WritePaths(IEnumerable<ViewField> projected)
    {
        foreach (var field in projected)
        {
            var requiredKind = field.RequiredKind is { } kind ? $"{Schema}LatticeFieldTypeEnum.{kind}" : "null";
            var requiredNullable = field.RequiredNullable switch { true => "true", false => "false", null => "null" };

            Line($"new({SymbolDisplay.FormatLiteral(field.Path, quote: true)}, {requiredKind}, {requiredNullable}),");
            WritePaths(field.Children);
        }
    }

    private void WriteProperties(IEnumerable<ViewField> projected)
    {
        var index = 0;
        foreach (var field in projected)
        {
            WriteProperty(field, index);
            index += field.FieldCount;
        }
    }

    private void WriteProperty(ViewField field, int index)
    {
        if (!SyntaxFacts.IsValidIdentifier(field.Name) && SyntaxFacts.GetKeywordKind(field.Name) == SyntaxKind.None)
        {
            throw ProjectionBuilder.Failure(field.Path, "the property name is not a C# identifier");
        }

        Line();
        var name = "@" + field.Name;
        var modifiers = field.Name is "Equals" or "GetHashCode" or "ToString" or "GetType" or "Finalize" or "MemberwiseClone"
            ? "public new"
            : "public";
        var value = $"{_record}[{_handles}[{index}]]";
        var clrType = field.ClrType;
        if (field.Kind == LatticeFieldTypeEnum.Binary || clrType.SpecialType == SpecialType.System_String)
        {
            Line($"{modifiers} {Access}LatticeValueView {name} => {value};");
            return;
        }

        if (FieldTypes.IsNested(field.Kind))
        {
            var (borrowedType, borrow) = field.Kind switch
            {
                LatticeFieldTypeEnum.Owned => OwnedBorrow(field, index),
                LatticeFieldTypeEnum.List => ($"{Access}LatticeListView", "item.List"),
                LatticeFieldTypeEnum.Map => ($"{Access}LatticeMapView", "item.Map"),
                _ => ($"{Access}LatticeSetView", "item.Set"),
            };

            if (field.IsNullable)
            {
                Open($"{modifiers} {Access}LatticeOptionalView<{borrowedType}> {name}");
                Open("get");
                Line($"var item = {value};");
                Line($"return item.IsNull ? default : new({borrow});");
                Close();
                Close();
            }
            else
            {
                Open($"{modifiers} {borrowedType} {name}");
                Open("get");
                Line($"var item = {value};");
                Line($"return {borrow};");
                Close();
                Close();
            }

            return;
        }

        var scalarType = clrType is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable
            ? nullable.TypeArguments[0]
            : clrType;
        var getter = Scalar(scalarType, field.IsNullable ? "item" : value);
        if (field.IsNullable)
        {
            Open($"{modifiers} {Qualified(clrType)} {name}");
            Open("get");
            Line($"var item = {value};");
            Line($"return item.IsNull ? null : {getter};");
            Close();
            Close();
        }
        else
        {
            Line($"{modifiers} {Qualified(clrType)} {name} => {getter};");
        }
    }

    private (string Type, string Expression) OwnedBorrow(ViewField field, int index)
    {
        var name = OwnedViewName(field);
        var childStart = index + 1;
        return (name, $"new {name}(item.Owned, {_handles}[{childStart}..])");
    }

    private string OwnedViewName(ViewField field)
    {
        foreach (var owned in _ownedViews)
        {
            if (SymbolEqualityComparer.Default.Equals(owned.Field.ClrType, field.ClrType) && SameFields(owned.Field.Children, field.Children))
            {
                return owned.Name;
            }
        }

        var name = UnusedName(field.ClrType.Name + "View");
        _ownedViews.Add((name, field));
        return name;
    }

    private static bool SameFields(ViewField[] left, ViewField[] right)
    {
        if (left.Length != right.Length)
        {
            return false;
        }

        for (var index = 0; index < left.Length; index++)
        {
            var a = left[index];
            var b = right[index];
            if (a.Name != b.Name || a.Kind != b.Kind || a.IsNullable != b.IsNullable ||
                !SymbolEqualityComparer.Default.Equals(a.ClrType, b.ClrType) || !SameFields(a.Children, b.Children))
            {
                return false;
            }
        }

        return true;
    }

    private string Scalar(ITypeSymbol type, string value)
    {
        if (type is INamedTypeSymbol { EnumUnderlyingType: { } underlying })
        {
            return $"({Qualified(type)}){value}.Get<{Qualified(underlying)}>()";
        }

        return $"{value}.Get<{Qualified(type)}>()";
    }

    private IEnumerable<INamedTypeSymbol> Containers()
    {
        var containers = new Stack<INamedTypeSymbol>();
        for (var enclosing = view.ContainingType; enclosing is not null; enclosing = enclosing.ContainingType)
        {
            containers.Push(enclosing);
        }

        return containers;
    }

    private static string Declaration(INamedTypeSymbol type)
    {
        var modifiers = type.IsStatic ? "static " : "";
        if (type.IsReadOnly)
        {
            modifiers += "readonly ";
        }

        if (type.IsRefLikeType)
        {
            modifiers += "ref ";
        }

        var kind = type.TypeKind switch
        {
            TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
            TypeKind.Interface => "interface",
            _ => type.IsRecord ? "record class" : "class",
        };

        return $"{modifiers}partial {kind} {Name(type)}";
    }

    private static string Name(INamedTypeSymbol type)
    {
        if (type.TypeParameters.Length == 0)
        {
            return "@" + type.Name;
        }

        var arguments = string.Join(", ", type.TypeParameters.Select(parameter => parameter.Variance switch
        {
            VarianceKind.In => "in @" + parameter.Name,
            VarianceKind.Out => "out @" + parameter.Name,
            _ => "@" + parameter.Name,
        }));
        return $"@{type.Name}<{arguments}>";
    }

    private string Qualified(ITypeSymbol type) => _types.Format(type);

    private void ReserveChildNames(IEnumerable<ViewField> parent)
    {
        foreach (var field in parent)
        {
            _names.Add(field.Name);
            ReserveChildNames(field.Children);
        }
    }
    private string UnusedName(string preferred)
    {
        var name = preferred;
        var suffix = 2;
        while (!_names.Add(name))
        {
            name = preferred + suffix;
            suffix++;
        }

        return name;
    }

    private void Open(string declaration)
    {
        Line(declaration);
        Line("{");
        _indent++;
    }

    private void Close()
    {
        _indent--;
        Line("}");
    }

    private void Line(string content = "")
    {
        if (content.Length != 0)
        {
            _source.Append(' ', _indent * 4).Append(content);
        }

        _source.AppendLine();
    }
}
